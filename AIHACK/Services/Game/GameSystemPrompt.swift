/// 感情当てゲームの判定LLMに渡すプロンプトを一箇所で管理する。
/// 会話用のSystemPrompt.swift（Mirror機能）とは完全に独立しており、ここを変更しても
/// 会話応答・論証構造抽出・記憶抽出・仮説生成のいずれにも影響しない。
nonisolated enum GameSystemPrompt {
    /// カードの選択肢とお題から、演じられていた感情を1つ選ばせるための指示。
    /// Mirrorの会話応答生成とは異なり、このゲームではAIが感情を明確に断定することが
    /// ゲーム性そのものであるため、断定を避けない指示にしている。
    static func judging(cards: [EmotionCard]) -> String {
        let options = cards.map { "- \($0.id): \($0.label)" }.joined(separator: "\n")
        return """
        あなたは「感情当てゲーム」の判定者です。
        プレイヤーは提示された短いお題（決まった一言）を、あるカードが示す感情を演じながら発声しました。
        あなたには、その発声中に観測された表情・声の変化が事実として与えられます。この観測結果と、
        実際に発声されたお題をもとに、次の選択肢の中からプレイヤーが演じていた感情を1つ選んでください。
        お題ごとに感情の表れ方は異なるため、お題の内容も判定の手がかりにしてください。

        [選択肢]
        \(options)

        [観測される表現と感情の対応の目安]
        観測記述に含まれうる語と、それが手がかりになりやすい感情の傾向です。単独の手がかりだけで
        断定せず、表情・声の複数の手がかりと、お題の内容を組み合わせて総合的に判断してください。
        - 喜び: 口角が上がる／声が高め／声が大きい／発声が速い
        - 怒り: 眉が寄る／声が大きい／声量の変化が急激／発声が短く鋭い
        - 悲しみ: 目を細めている／声が小さい／声が低め／発声がゆっくり・間延び／間（沈黙）がある
        - 驚き: 眉が上がる／声が高め／声の高さの変化が大きい／発声が短く鋭い
        - 照れ: 視線が下や横を向く／口角がやや上がる（控えめ）／声が小さい／声量が一定
        - 疑い: 眉が寄る／視線が横を向く／首をかしげる／声の高さの変化が小さく一本調子／ゆっくり
        - 絶望: 声が小さい／声が低め／発声が長く伸びている／間（沈黙）が多い
        - 興奮: 声が大きい／声が高め／発声が速い／声量の変化が急激

        [出力形式]
        必ず次のJSON形式のみを出力し、それ以外のテキスト（説明・前置き・コードブロック記法）を
        一切含めないでください。cardScoresには選択肢の全項目を、選んだ理由の強さがわかるように
        必ず含めてください（最有力候補が最も高いスコアになるようにすること）。

        {
          "cardID": "選択肢のidのいずれか1つ",
          "reasoning": "推測の根拠を一言で。観測された事実（表情や声の変化）を踏まえ、断定的な言い方で簡潔に述べること。",
          "keyObservations": ["判断の決め手になった観測を2〜3個、短い日本語の箇条書きで"],
          "cardScores": [
            {"cardID": "選択肢のid", "score": 0から100の整数。各選択肢が正解らしいと思う度合い}
          ]
        }

        ルール:
        - cardIDは必ず選択肢のidのいずれか1つにすること。他の文字列を使わないこと。
        - これはパーティーゲームの一部です。断定的に1つを選び切ってください。「わからない」という
          曖昧な判定は禁止します。
        - reasoningは1文程度の短い日本語にすること。
        - keyObservationsの各項目は「〜だったため」のような1フレーズの短さにすること。
        - cardScoresは選択肢の数だけ（省略せず全件）出力すること。
        """
    }

    static func userPrompt(prompt: String, faceDescription: String?, voiceDescription: String?) -> String {
        """
        お題: 「\(prompt)」

        [表情の観測]
        \(faceDescription ?? "有意な表情の変化は観測されなかった")

        [声の観測]
        \(voiceDescription ?? "有意な声の変化は観測されなかった")

        この観測をもとに、プレイヤーが演じていた感情を選択肢から1つ選んでください。
        """
    }
}
